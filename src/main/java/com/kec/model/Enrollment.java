package com.kec.model;

public class Enrollment {
    private int enrollmentId; // auto‑generated by DB
    private String rollNumber;
    private String courseCode;
    private int semester;
    private int totalClasses;
    private int attendedClasses;

    public Enrollment(int enrollmentId, String rollNumber, String courseCode, int semester, int totalClasses, int attendedClasses) {
        this.enrollmentId = enrollmentId;
        this.rollNumber = rollNumber;
        this.courseCode = courseCode;
        this.semester = semester;
        this.totalClasses = totalClasses;
        this.attendedClasses = attendedClasses;
    }

    // Constructor without enrollmentId (for inserts before DB generates id)
    public Enrollment(String rollNumber, String courseCode, int semester, int totalClasses, int attendedClasses) {
        this(-1, rollNumber, courseCode, semester, totalClasses, attendedClasses);
    }

    public int getEnrollmentId() { return enrollmentId; }
    public void setEnrollmentId(int enrollmentId) { this.enrollmentId = enrollmentId; }
    public String getRollNumber() { return rollNumber; }
    public String getCourseCode() { return courseCode; }
    public int getSemester() { return semester; }
    public int getTotalClasses() { return totalClasses; }
    public int getAttendedClasses() { return attendedClasses; }
    public double getAttendancePercentage() {
        return totalClasses == 0 ? 0.0 : (attendedClasses * 100.0) / totalClasses;
    }
}
